#!/usr/bin/env python3
"""Convert the Ash & Ember enemy SVGs (flat fills, fill-opacity, evenodd, simple strokes,
circles, <g fill=...>) into Android VectorDrawable XML. No gradients/filters/masks supported
(the enemy SVGs don't use them).

Usage: svg2vd.py [--calm] in.svg out.xml

--calm  Reduce-flash variant: Lantern Amber / Amber Core (#F2A541 / #FFD27A) are toned down —
        translucent glow halos keep 30% of their alpha, solid amber shapes 55%. Used for the
        `<id>_calm.xml` drawables shown when Settings > Reduce flashing is on."""
import re, sys
import xml.etree.ElementTree as ET

NS = '{http://www.w3.org/2000/svg}'
ATTRS = ['fill', 'fill-opacity', 'fill-rule', 'stroke', 'stroke-width', 'stroke-linecap',
         'stroke-linejoin', 'stroke-opacity', 'opacity']

def norm(d):
    return re.sub(r'\s+', ' ', d).strip()

def circle_path(cx, cy, r):
    f = lambda v: ('%.3f' % v).rstrip('0').rstrip('.')
    return 'M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 -%s,0 Z' % (
        f(cx - r), f(cy), f(r), f(r), f(2 * r), f(r), f(r), f(2 * r))

def color(c, op):
    c = c.strip()
    if c.startswith('#') and len(c) == 4:
        c = '#' + ''.join(ch * 2 for ch in c[1:])
    if op is not None and float(op) < 1.0:
        a = max(0, min(255, round(float(op) * 255)))
        return '#%02X%s' % (a, c[1:].upper())
    return c.upper()

AMBER = {'#F2A541', '#FFD27A'}
CALM = False

def calm_op(c, op):
    if not CALM:
        return op
    c = c.strip().upper()
    if len(c) == 4:
        c = '#' + ''.join(ch * 2 for ch in c[1:])
    if c not in AMBER:
        return op
    return op * (0.30 if op < 1.0 else 0.55)

def walk(el, inherited, out):
    st = dict(inherited)
    for a in ATTRS:
        if el.get(a) is not None:
            st[a] = el.get(a)
    tag = el.tag.replace(NS, '')
    d = None
    if tag == 'path':
        d = norm(el.get('d'))
    elif tag == 'circle':
        d = circle_path(float(el.get('cx')), float(el.get('cy')), float(el.get('r')))
    elif tag in ('svg', 'g'):
        for ch in el:
            walk(ch, st, out)
        return
    elif tag in ('title', 'desc', 'defs'):
        return
    else:
        raise SystemExit('unsupported element: ' + tag)
    attrs = ['android:pathData="%s"' % d]
    op = float(st.get('opacity', 1))
    fill = st.get('fill', '#000000')
    if fill != 'none':
        fo = calm_op(fill, float(st.get('fill-opacity', 1)) * op)
        attrs.append('android:fillColor="%s"' % color(fill, fo))
        if st.get('fill-rule') == 'evenodd':
            attrs.append('android:fillType="evenOdd"')
    stroke = st.get('stroke')
    if stroke and stroke != 'none':
        so = calm_op(stroke, float(st.get('stroke-opacity', 1)) * op)
        attrs.append('android:strokeColor="%s"' % color(stroke, so))
        attrs.append('android:strokeWidth="%s"' % st.get('stroke-width', '1'))
        if 'stroke-linecap' in st:
            attrs.append('android:strokeLineCap="%s"' % st['stroke-linecap'])
        if 'stroke-linejoin' in st:
            attrs.append('android:strokeLineJoin="%s"' % st['stroke-linejoin'])
    out.append('    <path\n        ' + '\n        '.join(attrs) + ' />')

def main(src, dst):
    root = ET.parse(src).getroot()
    vb = root.get('viewBox', '0 0 512 512').split()
    w, h = vb[2], vb[3]
    paths = []
    walk(root, {}, paths)
    with open(dst, 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write('<!-- Generated by tools/svg2vd.py%s from docs/art/ash_ember/%s. Original Ashen Lantern art. -->\n'
                % (' in calm mode (reduce-flash variant)' if CALM else '', src.split('docs/art/ash_ember/')[-1]))
        f.write('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                '    android:width="256dp"\n    android:height="256dp"\n'
                '    android:viewportWidth="%s"\n    android:viewportHeight="%s">\n' % (w, h))
        f.write('\n'.join(paths) + '\n</vector>\n')

if __name__ == '__main__':
    args = sys.argv[1:]
    if args and args[0] == '--calm':
        CALM = True
        args = args[1:]
    main(args[0], args[1])
